// D1 を Node の組み込み SQLite で代用して、受付サーバーの動作を確認する
import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import { handle } from './src/index.js';
const db = new DatabaseSync(':memory:');
db.exec(fs.readFileSync(new URL('./schema.sql', import.meta.url), 'utf8'));
const D1 = { prepare: sql => { const st = db.prepare(sql); let args = []; const o = {
  bind: (...a) => { args = a; return o; }, first: async () => st.get(...args), run: async () => st.run(...args), all: async () => ({ results: st.all(...args) }) }; return o; } };
const env = { DB: D1, SALT: 'test', ALLOW_ORIGIN: 'https://example.jp' };
const req = (method, path, body, ip = '1.2.3.4') => new Request('https://w.example' + path, { method, body: body && JSON.stringify(body), headers: { 'Content-Type': 'application/json', 'CF-Connecting-IP': ip } });
const results = []; const ok = (name, cond, detail = '') => { results.push({ name, ok: !!cond, detail }); };
const t0 = new Date('2026-11-02T10:00:00Z');
let r = await handle(req('POST', '/api/report', { ward: '北区', town: '赤羽西', kind: 'siren' }), env, t0);
ok('正しい報告を受け付ける', r.status === 200, r.status);
r = await handle(req('POST', '/api/report', { ward: '北区', town: '赤羽西', kind: 'smoke' }), env, new Date(+t0 + 60e3));
ok('同じ人・同じ区は10分以内なら断る', r.status === 429, r.status);
r = await handle(req('POST', '/api/report', { ward: '北区', kind: 'siren' }), env, new Date(+t0 + 11 * 60e3));
ok('10分たてば受け付ける', r.status === 200, r.status);
r = await handle(req('POST', '/api/report', { ward: '北区', town: '赤羽', kind: 'fire' }, '5.6.7.8'), env, new Date(+t0 + 2 * 60e3));
ok('別の人は受け付ける', r.status === 200, r.status);
r = await handle(req('POST', '/api/report', { ward: '大阪市北区', kind: 'siren' }), env, t0);
ok('23区以外の区名は断る', r.status === 400, r.status);
r = await handle(req('POST', '/api/report', { ward: '港区', kind: 'explosion' }), env, t0);
ok('決められた種類以外は断る', r.status === 400, r.status);
r = await handle(req('POST', '/api/report', { ward: '港区', town: '<script>', kind: 'siren' }, '9.9.9.9'), env, t0);
ok('町名にタグなどは入れられない', r.status === 400, r.status);
r = await handle(req('POST', '/api/report', { ward: '港区', town: '白金1丁目5番地3号', kind: 'siren' }, '8.8.8.8'), env, t0);
const row = db.prepare("SELECT town FROM reports WHERE ward='港区'").get();
ok('番地・号は切り捨てて保存', r.status === 200 && row && row.town === '白金1丁目', row && row.town);
const ipStored = db.prepare("SELECT COUNT(*) n FROM reports WHERE who LIKE '%1.2.3.4%'").get().n;
ok('IPアドレスをそのまま保存しない', ipStored === 0);
r = await handle(req('GET', '/api/reports?hours=24'), env, new Date(+t0 + 20 * 60e3));
const j = await r.json();
ok('区・町ごとの集計', j.wards['北区'].total === 3 && j.wards['北区'].siren === 2 && j.wards['北区'].fire === 1 && j.wards['北区'].towns['赤羽西'] === 1 && j.wards['港区'].total === 1, JSON.stringify(j.wards['北区']));
ok('他サイトからの読み込み許可（CORS）', r.headers.get('Access-Control-Allow-Origin') === 'https://example.jp');
r = await handle(req('GET', '/api/reports?hours=1'), env, new Date(+t0 + 5 * 3600e3));
ok('時間の範囲外は数えない', Object.keys((await r.json()).wards).length === 0);
const fails = results.filter(x => !x.ok);
results.forEach(x => console.log(`${x.ok ? 'PASS' : 'FAIL'}  ${x.name}${x.detail !== '' ? ' — ' + x.detail : ''}`));
fs.writeFileSync(new URL('../verify/worker.json', import.meta.url), JSON.stringify({ at: new Date().toISOString(), results }));
process.exit(fails.length ? 1 : 0);
